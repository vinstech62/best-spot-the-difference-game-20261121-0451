// Lantern Lane — Spot the Difference: the hand-in program. It copies the
// finished game and its screenshots into the output directory and writes
// the dossier exactly as the kit's library builds it, so the grader's own
// rebuild matches byte for byte. Standard library only; no network.

import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-game.ts';

const here = dirname(fileURLToPath(import.meta.url));
const out = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

mkdirSync(out, { recursive: true });
cpSync(join(here, 'game'), join(out, 'game'), { recursive: true });
mkdirSync(join(out, 'screenshots'), { recursive: true });
if (existsSync(join(here, 'screenshots'))) {
  cpSync(join(here, 'screenshots'), join(out, 'screenshots'), { recursive: true });
}

// The caps mirror the sealed gate's own: only text_max_bytes shapes the
// dossier bytes; the rest refuse here what the scorer would refuse there
// (too many screenshots or one too large; too many game files, too many
// bytes in all, or a path under game/ that runs too long).
writeFileSync(
  join(out, 'dossier.json'),
  buildDossier(out, {
    text_max_bytes: 163840,
    screenshots: { max: 4, max_bytes: 262144 },
    game_max_files: 993,
    game_max_bytes: 50331648,
    game_path_max_bytes: 1000,
  }),
);
